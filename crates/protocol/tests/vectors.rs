//! Cross-language test vectors for the web viewer (`viewer/test/vectors.json`).
//!
//! `cargo test` fails when the committed file differs from what this crate
//! produces; `UPDATE_VECTORS=1 cargo test -p plexusterm-share-protocol --test
//! vectors` rewrites it.

use std::path::PathBuf;

use plexusterm_share_protocol::content::{Access, ClientId, Content, SnapshotPart, Status};
use plexusterm_share_protocol::frame::{Binding, Direction, Sealer};
use plexusterm_share_protocol::keys::{Challenge, DerivedKeys, Role, Secret, ShareId};
use plexusterm_share_protocol::link::share_url;
use plexusterm_share_protocol::noise::{PendingViewer, ViewerHandshake};
use serde_json::{Value, json};

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

fn seq_bytes<const N: usize>(start: u8) -> [u8; N] {
    let mut out = [0u8; N];
    for (i, b) in out.iter_mut().enumerate() {
        *b = start.wrapping_add(i as u8);
    }
    out
}

fn vectors() -> Value {
    let share_id = ShareId(seq_bytes(0x10));
    let secret = Secret(seq_bytes(0x40));
    let challenge = Challenge(seq_bytes(0x80));
    let keys = DerivedKeys::derive(&secret);

    let viewer_e: [u8; 32] = seq_bytes(0xa0);
    let sharer_e: [u8; 32] = seq_bytes(0xc0);
    let hello = br#"{"client":"AAECAwQFBgcICQoLDA0ODw","resume_from":41}"#;
    let welcome = br#"{"access":"type","cols":120,"rows":40}"#;
    let (viewer, msg1) =
        ViewerHandshake::start_with_ephemeral(&share_id, &keys.psk, hello, &viewer_e).unwrap();
    let (pending, got_hello) =
        PendingViewer::accept_with_ephemeral(&share_id, &keys.psk, &msg1, &sharer_e).unwrap();
    assert_eq!(got_hello, hello);
    let (sharer_keys, msg2) = pending.respond(welcome).unwrap();
    let (viewer_keys, got_welcome) = viewer.finish(&msg2).unwrap();
    assert_eq!(got_welcome, welcome);
    assert_eq!(sharer_keys, viewer_keys);

    let binding = |direction| Binding {
        share_id,
        viewer_id: 7,
        direction,
    };
    let mut to_viewer = Sealer::new(&viewer_keys.to_viewer, binding(Direction::ToViewer));
    let mut to_sharer = Sealer::new(&viewer_keys.to_sharer, binding(Direction::ToSharer));
    let out1 = Content::Output {
        seq: 42,
        data: b"hello \x1b[1mworld\x1b[0m\r\n".to_vec(),
    }
    .encode();
    let out2 = Content::Status(Status {
        access: Some(Access::View),
        ..Status::default()
    })
    .encode();
    let input = Content::Input {
        data: b"ls -la\r".to_vec(),
    }
    .encode();

    let raw_snapshot = b"\x1b[2J\x1b[Hsnapshot line 1\r\nsnapshot line 2\r\n".repeat(20);
    let mut enc = flate2::write::DeflateEncoder::new(Vec::new(), flate2::Compression::default());
    std::io::Write::write_all(&mut enc, &raw_snapshot).unwrap();
    let compressed = enc.finish().unwrap();

    let contents = [
        (
            "output",
            Content::Output {
                seq: 258,
                data: b"ab".to_vec(),
            },
        ),
        (
            "snapshot",
            Content::Snapshot {
                covers_seq: 257,
                cols: 80,
                rows: 24,
                part: SnapshotPart::Screen,
                index: 1,
                count: 3,
                compressed: true,
                data: vec![0xde, 0xad],
            },
        ),
        (
            "status",
            Content::Status(Status {
                input_paused: Some(true),
                ..Status::default()
            }),
        ),
        ("size", Content::Size { cols: 300, rows: 50 }),
        ("input", Content::Input { data: b"\x03".to_vec() }),
        ("resync_some", Content::Resync { last_seq: Some(9) }),
        ("resync_none", Content::Resync { last_seq: None }),
    ];

    json!({
        "comment": "Generated by crates/protocol/tests/vectors.rs. Do not edit by hand.",
        "share_id": share_id.to_b64(),
        "secret": secret.to_b64(),
        "challenge": challenge.to_b64(),
        "link": share_url("https://view.example", &share_id, &secret),
        "derived": {
            "link_id": keys.link_id.to_b64(),
            "psk": hex(&keys.psk),
            "verifier": keys.verifier().to_b64(),
            "viewer_proof": keys.prove(Role::Viewer, &share_id, &challenge).to_b64(),
            "owner_proof": keys.prove(Role::Owner, &share_id, &challenge).to_b64(),
        },
        "client_id": ClientId(seq_bytes(0)).to_b64(),
        "noise": {
            "viewer_ephemeral": hex(&viewer_e),
            "sharer_ephemeral": hex(&sharer_e),
            "msg1_payload": String::from_utf8_lossy(hello),
            "msg1": hex(&msg1),
            "msg2_payload": String::from_utf8_lossy(welcome),
            "msg2": hex(&msg2),
            "to_sharer": hex(&viewer_keys.to_sharer),
            "to_viewer": hex(&viewer_keys.to_viewer),
        },
        "frames": {
            "viewer_id": 7,
            "to_viewer": [
                { "plaintext": hex(&out1), "frame": hex(&to_viewer.seal(&out1).unwrap()) },
                { "plaintext": hex(&out2), "frame": hex(&to_viewer.seal(&out2).unwrap()) },
            ],
            "to_sharer": [
                { "plaintext": hex(&input), "frame": hex(&to_sharer.seal(&input).unwrap()) },
            ],
        },
        "content": contents
            .iter()
            .map(|(name, c)| (name.to_string(), Value::String(hex(&c.encode()))))
            .collect::<serde_json::Map<_, _>>(),
        "deflate": {
            "raw": hex(&raw_snapshot),
            "compressed": hex(&compressed),
        },
    })
}

#[test]
fn committed_vectors_match_this_implementation() {
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../viewer/test/vectors.json");
    let generated = serde_json::to_string_pretty(&vectors()).unwrap() + "\n";
    if std::env::var_os("UPDATE_VECTORS").is_some() {
        std::fs::write(&path, &generated).unwrap();
        return;
    }
    let committed = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        committed == generated,
        "viewer/test/vectors.json is stale; run UPDATE_VECTORS=1 cargo test -p plexusterm-share-protocol --test vectors"
    );
}
